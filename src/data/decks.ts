export function pickAvatarTone(seed: string): string {
  let hash = 0;
  for (let i = 0; i < seed.length; i += 1) {
    hash = (hash * 31 + seed.charCodeAt(i)) >>> 0;
  }
  return AVATAR_TONES[hash % AVATAR_TONES.length];
}

export function extractInitials(name: string): string {
  const cleaned = name.trim();
  if (!cleaned) return 'א';
  const parts = cleaned.split(/\s+/).filter(Boolean);
  if (parts.length >= 2) {
    return `${parts[0][0]}${parts[1][0]}`.slice(0, 3);
  }
  return cleaned.slice(0, 2);
}

export function createDefaultTimeOptions(): Array<{
  id: string;
  label: string;
  dateIso: string;
  startTime: string;
}> {
  const now = new Date();
  const formatDay = (offset: number, time: string, prefix?: string) => {
    const d = new Date(now);
    d.setDate(d.getDate() + offset);
    const yyyy = d.getFullYear();
    const mm = String(d.getMonth() + 1).padStart(2, '0');
    const dd = String(d.getDate()).padStart(2, '0');
    const dayNames = ['ראשון', 'שני', 'שלישי', 'רביעי', 'חמישי', 'שישי', 'שבת'];
    const dayName = prefix ?? `יום ${dayNames[d.getDay()]}`;
    return {
      dateIso: `${yyyy}-${mm}-${dd}`,
      startTime: time,
      label: `${dayName} · ${time}`,
    };
  };

  return [
    { id: 'slot_today', ...formatDay(0, '20:30', 'היום') },
    { id: 'slot_tomorrow', ...formatDay(1, '20:00', 'מחר') },
    { id: 'slot_weekend', ...formatDay(3, '21:00') },
    { id: 'slot_alt', ...formatDay(4, '19:30') },
  ];
}
